import assert from "node:assert/strict";
import {planAppImport} from "../../../src/domain/appImportPlan.js";
import {catalogFor,defaultSources} from "./fixtures.js";
import {freshState,startLab,scanLab,placedIds,removeApp,moveApp,dissolveFolder,decodeLabState,importPlan,manualCandidates,placementPreview,applyPlacementPreview} from "./model.js";

const state=freshState();startLab(state);
assert.equal(state.items.filter(i=>i.kind==="folder").length,2);
assert.ok(state.items.some(i=>i.kind==="app"&&i.id==="pot"));
const vm=state.items.find(i=>i.kind==="folder"&&i.name==="工具合集");assert.ok(vm?.kind==="folder");
assert.equal(vm.apps.length,3,"equivalent source does not create another icon");
vm.name="虚拟机";state.installed.push("tools","extras");
const before=JSON.stringify(state.items);scanLab(state);
assert.ok(JSON.stringify(state.items).startsWith(before.slice(0,-1)),"scan appends without moving existing entries");
assert.equal(state.recent.length,4);applyPlacementPreview(state,placementPreview(state,state.recent),[]);
assert.ok(vm.apps.includes("tool-d"));assert.equal(vm.name,"虚拟机");
assert.ok(state.items.some(i=>i.kind==="folder"&&i.name==="附加应用组"));
const after=JSON.stringify(state.items);scanLab(state);assert.equal(JSON.stringify(state.items),after);
removeApp(state,"pot");scanLab(state);assert.ok(!placedIds(state).includes("pot"));
const restarted=decodeLabState(JSON.stringify(state));scanLab(restarted);assert.ok(!placedIds(restarted).includes("pot"));
applyPlacementPreview(restarted,placementPreview(restarted,[]),[]);assert.ok(!placedIds(restarted).includes("pot"));
applyPlacementPreview(restarted,placementPreview(restarted,["pot"]),[]);assert.ok(placedIds(restarted).includes("pot"));
removeApp(restarted,"pot",true);applyPlacementPreview(restarted,placementPreview(restarted,["pot"]),[]);assert.ok(!placedIds(restarted).includes("pot"));
const manual=freshState();startLab(manual);manual.installed.push("tools");scanLab(manual);moveApp(manual,"tool-d","desktop");applyPlacementPreview(manual,placementPreview(manual,manual.recent),[]);
assert.ok(manual.items.some(i=>i.kind==="app"&&i.id==="tool-d"),"user moved recent app stays put");
const f=manual.items.find(i=>i.kind==="folder"&&i.name==="工具合集")!;dissolveFolder(manual,f.id);scanLab(manual);
assert.ok(!manual.items.some(i=>i.kind==="folder"&&i.name==="工具合集"));
manual.offline=true;manual.installed.push("extras");const offlineBefore=JSON.stringify(manual.items);scanLab(manual);assert.equal(JSON.stringify(manual.items),offlineBefore);
const policies=defaultSources();policies[0]!.grouped=false;
const plan=planAppImport({apps:catalogFor([]),sources:policies,existingIds:[],hiddenIds:[],excludedIds:[]});
assert.ok(plan.singles.includes("tools"),"user source grouping preference wins even when equivalent system source groups");
assert.ok(plan.decisions.some(d=>d.id==="custom-tool"&&d.reason==="source-disabled"));
assert.throws(()=>decodeLabState('{"version":9}'));
const duplicate=freshState();startLab(duplicate);duplicate.items.push({kind:"app",id:"pot"});assert.throws(()=>decodeLabState(JSON.stringify(duplicate)));
assert.equal(importPlan(restarted).decisions.find(d=>d.id==="pot")!.reason,"excluded");
console.log("Import lab: initial grouping, incremental placement, restoration, provenance, manual overrides, incomplete scans and persistence passed");
const m=freshState();startLab(m);m.installed.push("extras","tools");
const offered=manualCandidates(m).map(r=>r.id),rows=placementPreview(m,["py","idle","tool-d"]);
assert.equal(rows.find(r=>r.ids.includes("tool-d"))?.target,m.items.find(i=>i.kind==="folder"&&i.name==="工具合集")?.id);
applyPlacementPreview(m,rows,offered);scanLab(m);
assert.equal(m.recent.length,0);assert.ok(!placedIds(m).includes("py-doc"));assert.ok(m.deferred?.includes("py-doc"));
assert.equal(manualCandidates(decodeLabState(JSON.stringify(m))).find(r=>r.id==="py-doc")?.status,"deferred");
const invalid=placementPreview(m,["py-doc"]);invalid[0]!.target="deleted-folder";const stable=JSON.stringify(m);
assert.throws(()=>applyPlacementPreview(m,invalid,["py-doc"]));assert.equal(JSON.stringify(m),stable);
console.log("Manual import: selected-only preview, existing folder suggestions, deferral, persistence and atomic validation passed");

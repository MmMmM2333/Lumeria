test('manual folders, dissolution and explicit exclusion survive scans',async({page})=>{
  await page.getByRole('button',{name:'跳过，使用默认布局'}).click();
  await page.getByRole('button',{name:'示例播放器',exact:true}).click();
  await page.locator('.edit-panel summary').click();
  await page.getByRole('textbox',{name:'新文件夹名称',exact:true}).fill('我的播放器');
  await page.getByRole('button',{name:'放入新文件夹'}).click();
  await expect(page.getByRole('button',{name:'我的播放器',exact:true})).toContainText('1 个应用');
  await page.getByRole('button',{name:'我的播放器',exact:true}).click();
  await page.getByRole('button',{name:'解散文件夹'}).click();
  await page.getByRole('button',{name:'↻ 自动扫描',exact:true}).click();
  await expect(page.getByRole('button',{name:'我的播放器',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'示例播放器',exact:true}).click();
  await page.locator('.edit-panel summary').click();
  await page.getByRole('button',{name:'排除此应用',exact:true}).click();
  await page.getByRole('button',{name:'手动扫描 / 恢复'}).click();
  await expect(page.getByRole('checkbox',{name:/示例播放器/})).toHaveCount(0);
  await page.getByRole('dialog').getByText('已排除 · 1').click();
  await page.getByRole('button',{name:'取消排除'}).click();
  await expect(page.getByRole('checkbox',{name:/示例播放器/})).not.toBeChecked();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'模拟重启',exact:true}).click();
  await expect(page.getByRole('button',{name:'示例播放器',exact:true})).toHaveCount(0);
});
test('manual scan first: select, preview, back, defer and no duplicate reminders',async({page})=>{
  await page.getByRole('button',{name:'跳过，使用默认布局'}).click();
  await page.getByRole('button',{name:/安装附加应用组/}).click();
  await page.getByRole('button',{name:'手动扫描 / 恢复'}).click();
  await expect(page.getByRole('checkbox',{name:/附加应用组/})).toBeChecked();
  await page.getByRole('checkbox',{name:/附加应用 C/}).uncheck();
  await page.getByRole('button',{name:/下一步（已选 2/}).click();
  await expect(page.locator('.placement-card')).toContainText('2 个应用');
  await page.getByRole('radio',{name:/启动台末尾/}).check();
  await page.getByRole('button',{name:'上一步：修改选择'}).click();
  await expect(page.getByRole('checkbox',{name:/附加应用 C/})).not.toBeChecked();
  await page.getByRole('button',{name:/下一步（已选 2/}).click();
  await expect(page.getByRole('radio',{name:/启动台末尾/})).toBeChecked();
  await page.getByRole('radio',{name:/新建「附加应用组」/}).check();
  await page.screenshot({path:'artifacts/import-lab-manual-preview.png',fullPage:true});
  await page.getByRole('button',{name:'确认添加',exact:true}).click();
  await expect(page.getByRole('button',{name:'附加应用组',exact:true})).toContainText('2 个应用');
  await page.getByRole('button',{name:'↻ 自动扫描',exact:true}).click();
  await expect(page.getByRole('button',{name:/＋ 新增/})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'附加应用 C',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'手动扫描 / 恢复'}).click();
  await expect(page.getByRole('checkbox',{name:/附加应用 C/})).not.toBeChecked();
  await expect(page.getByRole('dialog')).toContainText('此前暂不添加');
});

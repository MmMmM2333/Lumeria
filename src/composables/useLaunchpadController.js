export function createDeferredHandlers(defaults = {}) {
  const handlers = { ...defaults };
  const warned = new Set();

  function shouldWarn() {
    return Boolean(import.meta.env?.DEV) && typeof console !== "undefined" && typeof console.warn === "function";
  }

  function warnOnce(name) {
    if (!shouldWarn() || warned.has(name)) return;
    warned.add(name);
    console.warn(`LaunchPad deferred handler "${name}" was called before it was bound.`);
  }

  return {
    call(name, ...args) {
      const handler = handlers[name];
      if (typeof handler === "function") return handler(...args);
      warnOnce(name);
      return undefined;
    },
    set(name, handler) {
      if (typeof handler === "function") handlers[name] = handler;
      else delete handlers[name];
    },
  };
}

export function shouldPlayFolderOpenIconGhosts(next, state) {
  if (!next) return false;
  const openFolderId = state?.openFolderId?.value || null;
  const renderedFolderId = state?.renderedFolder?.value?.id || null;
  const isSameOpenFolder = openFolderId === next &&
    renderedFolderId === next &&
    !state?.isFolderClosing?.value &&
    !state?.isFolderAppLaunchClosing?.value;
  return !isSameOpenFolder;
}

function getSystemAppearance() {
  if (typeof window === "undefined" || typeof window.matchMedia !== "function") {
    return BACKGROUND_ACRYLIC_APPEARANCE_DARK;
  }
  return window.matchMedia("(prefers-color-scheme: light)").matches
    ? BACKGROUND_ACRYLIC_APPEARANCE_LIGHT
    : BACKGROUND_ACRYLIC_APPEARANCE_DARK;
}

function useSystemAppearance() {
  const systemAppearance = ref(getSystemAppearance());
  let mediaQuery = null;
  const update = () => {
    systemAppearance.value = getSystemAppearance();
  };

  onMounted(() => {
    if (typeof window === "undefined" || typeof window.matchMedia !== "function") return;
    mediaQuery = window.matchMedia("(prefers-color-scheme: light)");
    update();
    if (typeof mediaQuery.addEventListener === "function") {
      mediaQuery.addEventListener("change", update);
    } else {
      mediaQuery.addListener?.(update);
    }
  });

  onBeforeUnmount(() => {
    if (!mediaQuery) return;
    if (typeof mediaQuery.removeEventListener === "function") {
      mediaQuery.removeEventListener("change", update);
    } else {
      mediaQuery.removeListener?.(update);
    }
    mediaQuery = null;
  });

  return systemAppearance;
}


import assert from "node:assert/strict";
import { NativeTargetCheckCache } from "./nativeTargetCheckCache.js";
import type { LaunchTargetCheckRequest, LaunchTargetCheckResult } from "../platform/launchpadContracts.js";

let now = 0;
const requests: { targets: readonly LaunchTargetCheckRequest[]; force: boolean; resolve(results: readonly LaunchTargetCheckResult[]): void; reject(error: Error): void }[] = [];
const cache = new NativeTargetCheckCache((targets, force) => new Promise((resolve, reject) => requests.push({targets, force, resolve, reject})), () => now);
const a: LaunchTargetCheckRequest = { id: "a", launchTarget: {kind:"executable", path:"C:/a.exe"} };
const b: LaunchTargetCheckRequest = { id: "b", launchTarget: {kind:"appUserModelId", appUserModelId:"sample!App"} };
const ok = (id: string): LaunchTargetCheckResult => ({id, status:"ok"});
const first = cache.check([a,b]);
const shared = cache.check([b]);
assert.equal(requests.length, 1, "right-click shares an outstanding background batch");
requests[0]!.resolve([ok("a"),ok("b")]);
await Promise.all([first, shared]);
await cache.check([a]);
assert.equal(requests.length, 1);
now = 15_000;
const expired = cache.check([a]);
assert.equal(requests.length, 2);
requests[1]!.resolve([ok("a")]); await expired;
const forced = cache.check([a], true);
assert.equal(requests[2]!.force, true);
requests[2]!.resolve([ok("a")]); await forced;

const changed = cache.check([{...a, fallbackPaths:["C:/fallback.exe"]}]);
assert.equal(requests.length, 4, "fallback edits invalidate checks");
requests[3]!.reject(new Error("offline")); await assert.rejects(changed, /offline/);
const retry = cache.check([{...a, fallbackPaths:["C:/fallback.exe"]}]);
assert.equal(requests.length, 5, "failed checks are not cached");
requests[4]!.resolve([ok("a")]); await retry;

cache.clear();
const old = cache.check([a]);
const fresh = cache.check([a], true);
requests[6]!.resolve([{id:"a",status:"missing"}]); await fresh;
requests[5]!.resolve([ok("a")]); await old;
assert.equal((await cache.check([a]))[0]!.status, "missing", "late old results cannot replace forced cache entries");
cache.retain([b]);
const removed = cache.check([a]);
requests[7]!.resolve([ok("a")]); await removed;
assert.equal(requests.length, 8, "removed IDs do not retain their cache");
cache.clear();
const incomplete = cache.check([a]);
requests[8]!.resolve([]); await assert.rejects(incomplete, /Missing launch target/);
let uwpReads=0;
const uwpCache=new NativeTargetCheckCache(async targets=>{uwpReads++;return targets.map(target=>ok(target.id));});
await uwpCache.check([b]);await uwpCache.check([b]);
assert.equal(uwpReads,2,"UWP expiry is owned by the sidecar, not extended by another client TTL");
console.log("Native target check cache: batching, coalescing, expiry, forced refresh, edits, failures and removal passed");

export async function runNativeTargetActionsSmoke(o:{app:NativePixiApplication;apps:ReturnType<typeof createLaunchpadApps>;editing:ReturnType<typeof createNativeEditing>;folder:NativeFolderFlow;management:NativeManagement;dialogs:NativeAppDialogs;data:NativeDataHost;present(name:string):Promise<void>;check(force?:boolean):Promise<void>;menu(item:SceneItem,x:number,y:number):void;search(query:string):void;show():void;launching():boolean;showSettings():void;save():Promise<void>;quit():void|Promise<void>}):Promise<void>{
  const directory=process.env.LAUNCHPAD_TARGET_ACTIONS_PROOF!;mkdirSync(directory,{recursive:true});process.env.LAUNCHPAD_NATIVE_SMOKE_ARTIFACT_DIR=directory;
  const base=o.apps.managedApps.value.find(app=>app.launchTarget?.kind==="executable");assert.ok(base);
  o.apps.toggleMissingLaunchTargetBadge(true);o.apps.presentation.missingTargetStyle.value="question";
  const make=(id:string,name:string)=>({...base,id,name,origin:"manual" as const});
  const admin=make("proof-admin",labels.admin);
  const missing={...make("proof-missing",labels.missing),launchTarget:{kind:"executable",path:join(directory,"missing.exe")}};
  const folder={id:"proof-folder",type:"folder" as const,name:labels.folder,childPages:[[make("proof-a",labels.removeA),make("proof-b",labels.removeB),make("proof-c",labels.keepC)]]};
  o.editing.commit([[admin,missing,folder]]);await o.save();await o.check(true);await o.present("target badges");
  const capture=async(name:string)=>{await new Promise(resolve=>setTimeout(resolve,350));await o.present(name);await captureSmokeFrame(o.app,name);};
  const icon=(id:string)=>o.app.stage.getChildByLabel(`launchpad-item:${id}`,true) as Container & {state?:{badge?:IconBadge}};
  assert.equal(o.apps.nativeIntegration.getTargetDetails(missing.id)?.status,"missing");
  assert.equal(icon(missing.id).state?.badge?.missing,"question");
  await capture("targets-question");
  o.search(labels.query);await capture("targets-search");assert.equal(icon(missing.id).state?.badge?.missing,"question");o.search("");
  o.apps.presentation.missingTargetStyle.value="prohibited";await capture("targets-prohibited");
  assert.equal(icon(missing.id).state?.badge?.missing,"prohibited");
  o.menu(snapshotContractValue(missing) as SceneItem,190,160);await new Promise(resolve=>setTimeout(resolve,60));await capture("targets-missing-menu");
  const collect=(node:Container):NativeFluentButton[]=>[...(node instanceof NativeFluentButton?[node]:[]),...node.children.flatMap(collect)];
  const menuButtons=collect(o.management);assert.equal(menuButtons.find(button=>button.caption.text===t("common.actions.open"))?.disabled,true);
  assert.equal(menuButtons.find(button=>button.caption.text===t("common.actions.edit"))?.disabled,false);o.management.close();
  o.menu(snapshotContractValue(admin) as SceneItem,190,160);await new Promise(resolve=>setTimeout(resolve,80));await o.present("location menu");
  collect(o.management).find(button=>button.caption.text===t("launchpad.target.openLocation"))!.activate();
  for(let i=0;i<100&&o.app.window.isVisible();i++)await new Promise(resolve=>setTimeout(resolve,15));
  assert.equal(o.app.window.isVisible(),false,"file location hides launcher");o.show();await capture("targets-return-from-location");
  o.folder.open(snapshotContractValue(folder) as SceneItem);await new Promise(resolve=>setTimeout(resolve,450));await o.present("folder before removal");
  o.menu(snapshotContractValue(folder.childPages[0]![0]!) as SceneItem,190,160);await new Promise(resolve=>setTimeout(resolve,80));await o.present("folder location menu");
  collect(o.management).find(button=>button.caption.text===t("launchpad.target.openLocation"))!.activate();
  for(let i=0;i<100&&o.app.window.isVisible();i++)await new Promise(resolve=>setTimeout(resolve,15));
  assert.equal(o.app.window.isVisible(),false);o.show();await o.present("return to folder");
  assert.equal(o.folder.snapshot().renderedFolder?.id,folder.id,"location return keeps the current folder");
  o.apps.removeManagedAppFromLaunchpad("proof-a");await o.present("single removal");
  assert.deepEqual(o.folder.snapshot().renderedFolder?.childPages.flat().map(item=>item?.id),["proof-b","proof-c"]);
  o.apps.removeManagedAppsFromLaunchpad(["proof-b","proof-c"]);await o.present("batch removal");
  assert.ok(o.folder.snapshot().isClosing||!o.folder.snapshot().renderedFolder||o.folder.snapshot().renderedFolder?.childPages.flat().length===0);
  await capture("targets-folder-removed");
  writeFileSync(join(directory,"proof.json"),JSON.stringify({status:"passed",cases:["question","prohibited","location-hide","location-folder-return","missing-menu","folder-single-removal","folder-batch-removal"]},null,2));
  await o.quit();
}
